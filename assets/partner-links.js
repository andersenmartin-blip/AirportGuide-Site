/* Shared partner URLs and reporting for flight results and destination guides. */
(function () {
    'use strict';

    // Publisher-owned URLs retained from the existing site. Paste a complete
    // Viator-generated partner link here when available; never invent a PID.
    const links = Object.freeze({
        airalo: 'https://airalo.pxf.io/2RKYkg',
        kiwitaxi: 'https://kiwitaxi.tpo.mx/dUq07Ia1',
        airhelp: 'https://www.airhelp.com/en/?utm_medium=affiliate&utm_source=pap&utm_campaign=aff-69d37834e54fa&a_aid=69d37834e54fa&a_bid=b16056f0',
        viator: ''
    });

    // Replace with complete publisher-generated destination links once the
    // owner's programs have approved airportguideapp.com. Empty means use the
    // existing generic link, not an invented publisher ID or deep link.
    const dubaiLinks = Object.freeze({ airalo: 'https://airalo.pxf.io/KB66v9', kiwitaxi: 'https://kiwitaxi.tpo.mx/RyxrAcPa', viator: '' });

    function subId(context = {}) {
        const placement = ['dubai_guide', 'flight_result'].includes(context.placement) ? context.placement : 'site';
        const airport = /^[A-Z]{3}$/.test(context.airport || '') ? context.airport.toLowerCase() : 'general';
        // Only the named campaign is exported to partner reporting. Visitors'
        // arbitrary URL parameters and unique identifiers never go here.
        const paid = context.campaign === 'dubai_arrivals_test' ? 'dubai_test' : 'other';
        return `ag_${placement}_${airport}_${paid}`;
    }

    function decorate(offer, provider, context) {
        if (!offer || !offer.affiliate || !context) return offer;
        const url = new URL(offer.url);
        const id = subId(context);
        // Documented network parameters; publisher IDs and other fields stay.
        if (provider === 'airalo') url.searchParams.set('subId1', id);
        if (provider === 'kiwitaxi') url.searchParams.set('sub_id', id);
        return { ...offer, url: url.href, subId: ['airalo', 'kiwitaxi'].includes(provider) ? id : '' };
    }

    function resolve(provider, destination = '', configuredLinks = links, context) {
        const configured = configuredLinks[provider];
        if (provider === 'viator') {
            const fallback = new URL('https://www.viator.com/searchResults/all');
            fallback.searchParams.set('text', destination || 'Dubai');
            if (!configured) return { url: fallback.href, affiliate: false };
            try {
                const url = new URL(configured);
                if (url.protocol !== 'https:' || !['www.viator.com', 'viator.com'].includes(url.hostname)) {
                    return { url: fallback.href, affiliate: false };
                }
                // Keep all partner parameters intact. Destination search links can
                // be reused without stripping the attribution generated by Viator.
                if (url.pathname.startsWith('/searchResults/')) url.searchParams.set('text', destination || 'Dubai');
                const affiliate = ['pid', 'mcid', 'medium'].every(key => Boolean(url.searchParams.get(key)));
                return decorate({ url: url.href, affiliate }, provider, context);
            } catch (_) {
                return { url: fallback.href, affiliate: false };
            }
        }
        if (!configured) return null;
        try {
            const url = new URL(configured);
            if (url.protocol !== 'https:' || url.username || url.password) return null;
            const affiliate = (
                (provider === 'airalo' && url.hostname === 'airalo.pxf.io' && url.pathname.length > 1) ||
                (provider === 'kiwitaxi' && url.hostname === 'kiwitaxi.tpo.mx' && url.pathname.length > 1) ||
                (provider === 'airhelp' && url.hostname === 'www.airhelp.com' && Boolean(url.searchParams.get('a_aid')) && Boolean(url.searchParams.get('a_bid')))
            );
            if (!affiliate) return null;
            return decorate({ url: url.href, affiliate }, provider, context);
        } catch (_) {
            return null;
        }
    }

    function report(name, parameters) {
        // Navigation and flight lookup must also work when analytics is blocked.
        try {
            if (typeof window.gtag === 'function') window.gtag('event', name, parameters);
        } catch (_) {}
    }

    function parameters(link) {
        return {
            provider: link.dataset.provider,
            placement: link.dataset.placement || 'unknown',
            arrival_airport: document.body.dataset.arrivalAirport || '',
            monetized: link.dataset.affiliate === 'true',
            partner_sub_id: link.dataset.partnerSubId || ''
        };
    }

    let observer;
    function refresh(context = {}) {
        if (context.airport) document.body.dataset.arrivalAirport = context.airport;
        document.querySelectorAll('a[data-provider]').forEach(link => {
            const airport = document.body.dataset.arrivalAirport || '';
            const configured = airport === 'DXB' ? Object.fromEntries(Object.entries(links).map(([provider, url]) => [provider, dubaiLinks[provider] || url])) : links;
            const offer = resolve(link.dataset.provider, link.dataset.destination || '', configured, {
                airport, placement: link.dataset.placement,
                campaign: window.AirportGuideAnalytics?.campaign?.utm_campaign || ''
            });
            if (!offer) return;
            link.href = offer.url;
            link.dataset.affiliate = String(offer.affiliate);
            link.dataset.partnerSubId = offer.subId || '';
            link.rel = offer.affiliate ? 'noopener sponsored' : 'noopener';
        });

        if (observer) observer.disconnect();
        if (typeof IntersectionObserver !== 'function') return;
        const seen = new WeakSet();
        observer = new IntersectionObserver(entries => {
            entries.forEach(entry => {
                if (!entry.isIntersecting || entry.intersectionRatio < 0.5 || seen.has(entry.target)) return;
                const link = entry.target.querySelector('a[data-provider]');
                if (!link) return;
                // Do not mark an impression as measured before consent. The
                // observer is restarted when analytics becomes available.
                seen.add(entry.target);
                report('offer_impression', parameters(link));
            });
        }, { threshold: 0.5 });
        document.querySelectorAll('[data-offer-card]').forEach(card => observer.observe(card));
    }

    function handleClick(event) {
        if (event.type === 'auxclick' && event.button !== 1) return;
        const link = event.target.closest('a');
        if (!link) return;
        if (link.hasAttribute('data-guide-link')) {
            report('destination_guide_click', { guide: 'dubai', placement: link.dataset.placement || 'unknown' });
        }
        if (!link.dataset.provider) return;
        const params = parameters(link);
        report(params.monetized ? 'affiliate_click' : 'outbound_click', params);
        // Keep existing GA reports usable while adding one comparable event name.
        const legacy = { airalo: 'click_esim', kiwitaxi: 'click_taxi', airhelp: 'click_airhelp', viator: 'click_tours' };
        if (params.monetized && legacy[params.provider]) report(legacy[params.provider], { event_category: 'affiliate', ...params });
    }

    document.addEventListener('click', handleClick);
    document.addEventListener('auxclick', handleClick);
    document.addEventListener('airportguide:analytics-ready', () => refresh());
    window.AirportGuidePartners = Object.freeze({ resolve, refresh, links, subId });
    refresh();
    // The consent loader owns guide views, including consent granted later.
})();
